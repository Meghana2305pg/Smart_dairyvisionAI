"""Isolated scenario simulations for the digital-twin layer.

The scenario engine creates temporary, read-only simulations based on existing
snapshots. It reuses the existing prediction, health, explainability, and
recommendation services without mutating any live twin objects or underlying
history stores.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

from webapp.backend_services.explainability_service import get_explanation_for_input
from webapp.backend_services.health_service import get_health_alerts_for_input
from webapp.backend_services.prediction_service import predict_milk_yield
from webapp.digital_twin.decision_support import build_recommendations
from webapp.digital_twin.observation import Observation

from .memory.memory_store import InMemorySnapshotStore
from .memory.snapshot import TwinSnapshot


@dataclass(slots=True)
class Scenario:
    """A temporary digital-twin scenario built from a historical snapshot.

    Attributes:
        scenario_id: Stable identifier for the temporary scenario.
        cow_id: Cow the scenario is anchored to.
        created_at: Timestamp of scenario creation.
        name: Short scenario name.
        description: Human-readable scenario description.
        base_snapshot_id: Snapshot used as the starting point.
        modified_inputs: Dictionary of overridden values for the scenario.
        prediction: Predicted milk yield for the modified inputs.
        health_assessment: Health result produced by the existing health service.
        explainability: Explainability output from the existing service.
        recommendations: Recommendations generated by the existing recommendation logic.
        weather: Weather payload for the scenario.
        metadata: Additional scenario tracing data.
    """

    scenario_id: str
    cow_id: str
    created_at: datetime
    name: str
    description: str
    base_snapshot_id: str
    modified_inputs: dict[str, Any]
    prediction: dict[str, Any] | None = None
    health_assessment: dict[str, Any] | None = None
    explainability: list[dict[str, Any]] | None = None
    recommendations: list[dict[str, Any]] | None = None
    weather: dict[str, Any] | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class ScenarioComparison:
    """Difference summary between the live twin state and a scenario."""

    current_prediction: dict[str, Any] | None
    scenario_prediction: dict[str, Any] | None
    milk_difference: float | None = None
    health_difference: str | None = None
    recommendation_difference: int | None = None
    weather_difference: dict[str, Any] | None = None
    changed_features: list[str] = field(default_factory=list)


class ScenarioEngine:
    """Create isolated, read-only twin simulations from stored snapshots.

    The engine never mutates the live twin, snapshot history, timeline, playback
    cursor, or any other runtime state. It simply derives a temporary scenario
    from an existing snapshot and reuses the existing backend services.
    """

    def __init__(self, store: InMemorySnapshotStore | None = None) -> None:
        """Create a scenario engine optionally bound to a snapshot store."""
        self.store = store or InMemorySnapshotStore()
        self._scenarios: dict[str, Scenario] = {}

    def create_scenario(
        self,
        cow_id: str,
        base_snapshot_id: str,
        name: str,
        description: str,
        modified_inputs: dict[str, Any] | None = None,
    ) -> Scenario:
        """Create a new scenario from an existing snapshot.

        The scenario always starts from an existing snapshot, and the snapshot is
        never changed. A temporary observation is synthesized from the snapshot
        data and adjusted for the requested input overrides.
        """
        snapshot = self.store.load_snapshot(base_snapshot_id)
        if snapshot is None:
            raise ValueError(f"Unknown snapshot: {base_snapshot_id}")

        observation = self._build_observation(snapshot, modified_inputs or {})
        scenario_id = f"scenario-{cow_id}-{len(self._scenarios) + 1}"
        scenario = Scenario(
            scenario_id=scenario_id,
            cow_id=cow_id,
            created_at=datetime.utcnow(),
            name=name,
            description=description,
            base_snapshot_id=base_snapshot_id,
            modified_inputs=modified_inputs or {},
        )

        self._scenarios[scenario_id] = scenario
        self.apply_changes(scenario, observation)
        return scenario

    def clone_snapshot(self, snapshot: TwinSnapshot) -> TwinSnapshot:
        """Return a copy of a snapshot for use as the starting point of a scenario."""
        return TwinSnapshot(
            snapshot_id=f"{snapshot.snapshot_id}-clone",
            cow_id=snapshot.cow_id,
            timestamp=snapshot.timestamp,
            observation=snapshot.observation,
            prediction=snapshot.prediction,
            health=snapshot.health,
            weather=snapshot.weather,
            explanation=snapshot.explanation,
            recommendations=snapshot.recommendations,
            twin_status=snapshot.twin_status,
            metadata=dict(snapshot.metadata),
            health_assessment=snapshot.health_assessment,
            explainability=snapshot.explainability,
            version=snapshot.version,
        )

    def apply_changes(self, scenario: Scenario, observation: Observation | None = None) -> Scenario:
        """Apply the requested modifications to a scenario without touching live state."""
        snapshot = self.store.load_snapshot(scenario.base_snapshot_id)
        if snapshot is None:
            raise ValueError(f"Unknown snapshot: {scenario.base_snapshot_id}")

        resolved_observation = observation or self._build_observation(snapshot, scenario.modified_inputs)
        scenario.prediction = self.run_prediction(resolved_observation)
        scenario.health_assessment = self.run_health(resolved_observation, scenario.prediction)
        scenario.explainability = self.run_explainability(resolved_observation)
        scenario.weather = self._resolve_weather(resolved_observation)
        scenario.recommendations = self.run_recommendations(scenario.health_assessment)
        scenario.metadata.update(
            {
                "source": "scenario_engine",
                "base_snapshot_id": scenario.base_snapshot_id,
                "applied_modifications": sorted(scenario.modified_inputs.keys()),
            }
        )
        return scenario

    def run_prediction(self, observation: Observation) -> dict[str, Any] | None:
        """Reuse the existing prediction service for a temporary observation."""
        input_row = observation.to_input_row()
        try:
            return predict_milk_yield(input_row, base_temp=observation.temperature or 28.0, base_hum=observation.humidity or 65.0)
        except Exception:
            return None

    def compare_with_live(self, scenario: Scenario, live_snapshot: TwinSnapshot) -> ScenarioComparison:
        """Compare a scenario against the live snapshot and summarize differences."""
        current_prediction = live_snapshot.prediction or {}
        scenario_prediction = scenario.prediction or {}
        current_value = current_prediction.get("prediction")
        scenario_value = scenario_prediction.get("prediction")
        milk_difference = None
        if current_value is not None and scenario_value is not None:
            milk_difference = scenario_value - current_value

        health_difference = None
        if live_snapshot.health and scenario.health_assessment:
            health_difference = str(scenario.health_assessment.get("severity", "unknown"))

        recommendation_difference = None
        if live_snapshot.recommendations and scenario.recommendations:
            recommendation_difference = len(scenario.recommendations) - len(live_snapshot.recommendations)

        weather_difference = None
        if live_snapshot.weather or scenario.weather:
            weather_difference = {
                "current": live_snapshot.weather,
                "scenario": scenario.weather,
            }

        changed_features = sorted(scenario.modified_inputs.keys())
        return ScenarioComparison(
            current_prediction=current_prediction,
            scenario_prediction=scenario_prediction,
            milk_difference=milk_difference,
            health_difference=health_difference,
            recommendation_difference=recommendation_difference,
            weather_difference=weather_difference,
            changed_features=changed_features,
        )

    def delete_scenario(self, scenario_id: str) -> None:
        """Remove a previously created scenario from the isolated registry."""
        self._scenarios.pop(scenario_id, None)

    def list_scenarios(self) -> list[Scenario]:
        """Return all stored scenarios in creation order."""
        return list(self._scenarios.values())

    def run_health(self, observation: Observation, prediction: dict[str, Any] | None) -> dict[str, Any] | None:
        """Reuse the existing health service for a temporary observation."""
        input_row = observation.to_input_row()
        try:
            return get_health_alerts_for_input(
                input_row,
                base_temp=observation.temperature or 28.0,
                base_hum=observation.humidity or 65.0,
                predicted_yield=prediction.get("prediction") if prediction else None,
            )
        except Exception:
            return None

    def run_explainability(self, observation: Observation) -> list[dict[str, Any]] | None:
        """Reuse the existing explainability service for a temporary observation."""
        try:
            return get_explanation_for_input(
                observation.to_input_row(),
                base_temp=observation.temperature or 28.0,
                base_hum=observation.humidity or 65.0,
            )
        except Exception:
            return None

    def run_recommendations(self, health_assessment: dict[str, Any] | None) -> list[dict[str, Any]] | None:
        """Reuse the existing recommendation logic for the scenario."""
        if health_assessment is None:
            return None
        return [
            {"message": recommendation.message, "priority": recommendation.priority}
            for recommendation in [
                *build_recommendations(
                    type("ScenarioCow", (), {"latest_health": health_assessment})(),
                )
            ]
        ]

    def _resolve_weather(self, observation: Observation) -> dict[str, Any] | None:
        """Resolve scenario weather from the observation inputs."""
        return {"temperature": observation.temperature, "humidity": observation.humidity}

    def _build_observation(self, snapshot: TwinSnapshot, modified_inputs: dict[str, Any]) -> Observation:
        """Create a temporary observation from an existing snapshot and overrides."""
        base_observation = snapshot.observation or Observation(cow_id=snapshot.cow_id)
        payload = {
            "cow_id": snapshot.cow_id,
            "age": base_observation.age,
            "weight": base_observation.weight,
            "feed": base_observation.feed,
            "temperature": base_observation.temperature,
            "humidity": base_observation.humidity,
            "health_status": base_observation.health_status,
            "timestamp": snapshot.timestamp,
            "notes": base_observation.notes,
        }

        for key, value in modified_inputs.items():
            if key == "temperature":
                payload["temperature"] = value
            elif key == "humidity":
                payload["humidity"] = value
            elif key == "feed_intake":
                payload["feed"] = value
            elif key == "body_weight":
                payload["weight"] = value
            elif key == "age":
                payload["age"] = value
            elif key == "weather":
                payload["temperature"] = value.get("temperature", payload["temperature"])
                payload["humidity"] = value.get("humidity", payload["humidity"])
            elif key == "observation_values":
                for field_name, field_value in value.items():
                    if field_name in payload:
                        payload[field_name] = field_value

        return Observation(**payload)
